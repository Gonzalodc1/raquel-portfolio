const metaDescription = document.querySelector('meta[name="description"]');

// Snapshot del español tal y como está escrito en el HTML.
const ES = {
  "meta.title": document.title,
  "meta.description": metaDescription ? metaDescription.content : "",
};

const textNodes = document.querySelectorAll("[data-i18n]");
const altNodes = document.querySelectorAll("[data-i18n-alt]");
const ariaNodes = document.querySelectorAll("[data-i18n-aria-label]");

textNodes.forEach((el) => {
  const key = el.dataset.i18n;
  if (!(key in ES)) ES[key] = el.textContent.trim();
});
altNodes.forEach((el) => {
  const key = el.dataset.i18nAlt;
  if (!(key in ES)) ES[key] = el.alt;
});
ariaNodes.forEach((el) => {
  const key = el.dataset.i18nAriaLabel;
  if (!(key in ES)) ES[key] = el.getAttribute("aria-label");
});

const dictionaries = { es: ES, en: EN };
const langButtons = document.querySelectorAll(".lang-btn");

function applyLang(lang) {
  const dict = dictionaries[lang] || ES;
  const fallback = ES;
  const t = (key) => (dict[key] !== undefined ? dict[key] : fallback[key]);

  textNodes.forEach((el) => {
    const value = t(el.dataset.i18n);
    if (value !== undefined) el.textContent = value;
  });
  altNodes.forEach((el) => {
    const value = t(el.dataset.i18nAlt);
    if (value !== undefined) el.alt = value;
  });
  ariaNodes.forEach((el) => {
    const value = t(el.dataset.i18nAriaLabel);
    if (value !== undefined) el.setAttribute("aria-label", value);
  });

  document.documentElement.lang = lang;
  document.title = t("meta.title");
  if (metaDescription) metaDescription.content = t("meta.description");

  langButtons.forEach((btn) => {
    const isActive = btn.dataset.lang === lang;
    btn.classList.toggle("is-active", isActive);
    btn.setAttribute("aria-pressed", String(isActive));
  });

  try {
    localStorage.setItem(STORAGE_KEY, lang);
  } catch (err) {
    /* almacenamiento no disponible: el idioma simplemente no se recuerda */
  }
}

langButtons.forEach((btn) => {
  btn.addEventListener("click", () => applyLang(btn.dataset.lang));
});

function initialLang() {
  let stored = null;
  try {
    stored = localStorage.getItem(STORAGE_KEY);
  } catch (err) {
    /* ignorar */
  }
  if (stored === "es" || stored === "en") return stored;
  const browser = (navigator.language || "es").toLowerCase();
  return browser.startsWith("es") ? "es" : "en";
}

applyLang(initialLang());
